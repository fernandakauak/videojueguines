export function obtenerJuegos() {
  return new Promise((resolve) => {
    setTimeout(() => {
      resolve(juegos)
    }, 400)
  })
}

export function obtenerJuegoPorId(id) {
  return new Promise((resolve) => {
    setTimeout(() => {
      const juego = juegos.find((j) => j.id === Number(id))
      resolve(juego || null)
    }, 400)
  })
}